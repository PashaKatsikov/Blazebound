// ignore_for_file: avoid_print
// ============================================================
// GEN RELAY VEIL — encode the native transport's secret strings
// ============================================================
// The native relay (android/rust/relay_transport) must never carry the
// config URL, HTTP method, header names or MIME as plaintext literals —
// those strings would show up in a `strings libblazebound_relay.so`
// dump and cluster the endpoint. This generator XOR-encodes each secret
// with the position_xor family (the same codec the Dart app uses, but a
// SEPARATE salt) and writes `src/veil.rs`, which decodes them at runtime.
//
// Run after changing any secret:
//   dart run tool/gen_relay_veil.dart
// ============================================================

import 'dart:io';

import 'forge/codecs/position_xor.dart' as pxor;

// Independent salt + stream length for the native side. Rotating these
// does not touch the Dart app codec (lib/midway/cipher/unmask.dart).
const List<int> _salt = <int>[
  0x8E, 0x21, 0xC4, 0x5B, 0x0F, 0xA3, 0x77, 0xD9,
  0x12, 0x6B, 0xE0, 0x34, 0x9C, 0x58, 0xBD, 0x41,
  0x2F, 0xF6, 0x83, 0x70,
];
const int _streamLen = 32;

// The secrets, keyed by the Rust accessor name they back.
const Map<String, String> _secrets = <String, String>{
  'url': 'https://blazebound.online/config.php',
  'method': 'POST',
  'accept_name': 'Accept',
  'accept_value': 'application/json',
  'content_type_name': 'Content-Type',
  // MIME for the request body (Content-Type value).
  'mime': 'application/json',
};

String _rustArray(List<int> bytes) {
  final StringBuffer buf = StringBuffer('&[');
  for (int i = 0; i < bytes.length; i++) {
    if (i % 12 == 0) buf.write('\n    ');
    buf.write('0x${bytes[i].toRadixString(16).padLeft(2, '0')}, ');
  }
  buf.write('\n]');
  return buf.toString();
}

void main() {
  // Verify every secret round-trips before writing.
  for (final MapEntry<String, String> e in _secrets.entries) {
    if (!pxor.roundTripsPositionXor(
      plain: e.value,
      salt: _salt,
      streamLen: _streamLen,
    )) {
      stderr.writeln('veil: ${e.key} does not round-trip');
      exit(64);
    }
  }

  final StringBuffer out = StringBuffer();
  out.writeln('// ============================================================');
  out.writeln('// VEIL — generated by tool/gen_relay_veil.dart. Do NOT hand-edit.');
  out.writeln('// ============================================================');
  out.writeln('// position_xor family: additive salt fold -> xorshift32');
  out.writeln('// keystream -> per-byte XOR with keystream[i%len] ^ posMask(i).');
  out.writeln('// Mirrors lib/midway/cipher/unmask.dart with an independent salt,');
  out.writeln('// so no config URL / method / header / MIME literal lands in the .so.');
  out.writeln();
  out.writeln('const WEYL: u32 = 0x9E37_79B1;');
  out.writeln('const STREAM_LEN: usize = $_streamLen;');
  out.writeln();
  out.write('const SALT: &[u8] = ');
  out.write(_rustArray(_salt));
  out.writeln(';');
  out.writeln();
  for (final MapEntry<String, String> e in _secrets.entries) {
    final List<int> enc = pxor.encodePositionXor(
      plain: e.value,
      salt: _salt,
      streamLen: _streamLen,
    );
    final String name = 'VEIL_${e.key.toUpperCase()}';
    out.write('const $name: &[u8] = ');
    out.write(_rustArray(enc));
    out.writeln(';');
    out.writeln();
  }

  out.writeln(r'''
fn keystream() -> [u8; STREAM_LEN] {
    let mut acc: u32 = 0x243F_6A88;
    for (i, &b) in SALT.iter().enumerate() {
        acc = acc
            .wrapping_add((b as u32).wrapping_mul((i as u32) + 1))
            .wrapping_add(WEYL);
    }
    let mut state: u32 = if acc == 0 { WEYL } else { acc };
    let mut stream = [0u8; STREAM_LEN];
    for slot in stream.iter_mut() {
        state ^= state << 13;
        state ^= state >> 17;
        state ^= state << 5;
        *slot = ((state >> 16) & 0xFF) as u8;
    }
    stream
}

#[inline]
fn position_mask(i: usize) -> u8 {
    (((i as u64).wrapping_mul(WEYL as u64) >> 16) & 0xFF) as u8
}

fn reveal(encoded: &[u8]) -> String {
    if encoded.is_empty() {
        return String::new();
    }
    let stream = keystream();
    let mut out = Vec::with_capacity(encoded.len());
    for (i, &byte) in encoded.iter().enumerate() {
        out.push(byte ^ stream[i % STREAM_LEN] ^ position_mask(i));
    }
    String::from_utf8_lossy(&out).into_owned()
}

pub(crate) fn url() -> String { reveal(VEIL_URL) }
pub(crate) fn method() -> String { reveal(VEIL_METHOD) }
pub(crate) fn accept_name() -> String { reveal(VEIL_ACCEPT_NAME) }
pub(crate) fn accept_value() -> String { reveal(VEIL_ACCEPT_VALUE) }
pub(crate) fn content_type_name() -> String { reveal(VEIL_CONTENT_TYPE_NAME) }
pub(crate) fn mime() -> String { reveal(VEIL_MIME) }
''');

  const String path = 'android/rust/relay_transport/src/veil.rs';
  File(path)
    ..parent.createSync(recursive: true)
    ..writeAsStringSync(out.toString());
  print('wrote: $path (${_secrets.length} secrets, salt ${_salt.length}B, '
      'streamLen $_streamLen)');
}
